export function questionsForPage(file, service) {
  if (!service) return companyQuestions[file] || generalQuestions;
  const questions = [...service.questions, generalQuestions[2], generalQuestions[0], generalQuestions[1], generalQuestions[3]];
  const unique = new Map(questions.map(question => [question[0], question]));
  return [...unique.values()].slice(0, 4);
}

export function faqSection(questions) {
  return `<section class="section container faq-section" id="questions" aria-labelledby="questions-title">
    <div class="section-heading"><div><h2 id="questions-title">Вопросы и ответы</h2></div></div>
    <div class="faq-list">${questions.map(([question, answer]) => `
      <details class="faq"><summary>${escapeHTML(question)}<span aria-hidden="true">+</span></summary><p>${escapeHTML(answer)}</p></details>`).join('')}
    </div>
  </section>`;
}
